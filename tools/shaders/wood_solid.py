"""Writes souls_wood_solid.fsh/.json from souls_wood.fsh/.json: the same wood with no `discard`.

A shader that can discard turns the GPU's early depth test off for everything it draws, so every hidden layer of the
Buddha's fan of hands still ran the whole wood shader (issue #387). HsWood draws the pieces that can't discard (no
splintering, fully grown) with this copy. Edit souls_wood.fsh, then run: python3 tools/shaders/wood_solid.py
"""
import json
import os
import re

CORE = os.path.join(os.path.dirname(__file__), "..", "..", "src", "main", "resources", "assets", "battlegroundsmod", "shaders", "core")

with open(os.path.join(CORE, "souls_wood.fsh"), encoding="utf-8") as fh:
    src = fh.read()
out, n = re.subn(r"\)\s*discard;", ") {}", src)
assert "discard" not in out, "a discard left in a form this script does not know"
head = "// GENERATED by tools/shaders/wood_solid.py from souls_wood.fsh (no discard, so early depth stays on). Do not edit.\n"
lines = out.split("\n", 1)
with open(os.path.join(CORE, "souls_wood_solid.fsh"), "w", encoding="utf-8") as fh:
    fh.write(lines[0] + "\n" + head + lines[1])
with open(os.path.join(CORE, "souls_wood.json"), encoding="utf-8") as fh:
    js = json.load(fh)
js["fragment"] = "battlegroundsmod:souls_wood_solid"
with open(os.path.join(CORE, "souls_wood_solid.json"), "w", encoding="utf-8") as fh:
    json.dump(js, fh, indent=4)
    fh.write("\n")
print("souls_wood_solid: %d discards taken out" % n)
